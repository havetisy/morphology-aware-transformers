def main():
    """Main training and evaluation pipeline"""

    print("\n" + "="*70)
    print("FRAMING DETECTION WITH BERT - Main Experiment")
    print("="*70 + "\n")

    # Set seed for reproducibility
    set_seed(42)

    # Load tokenizer
    tokenizer = BertTokenizer.from_pretrained(Config.MODEL_NAME, do_lower_case=True)
    print(f"✓ Loaded tokenizer: {Config.MODEL_NAME}")

    # Load and prepare training data
    print(f"\n{'='*70}")
    print("Loading training data...")
    print(f"{'='*70}")
    train_df = load_and_prepare_data(Config.TRAIN_FILE, include_features=True)

    # Split data
    X = train_df.tweet.values
    y = train_df.label.values

    X_train, X_val, y_train, y_val = train_test_split(
        X, y,
        test_size=Config.VAL_SIZE,
        random_state=Config.RANDOM_STATE
    )

    print(f"\nTrain set: {X_train.shape[0]} samples")
    print(f"Validation set: {X_val.shape[0]} samples")

    # Tokenize data
    print(f"\n{'='*70}")
    print("Tokenizing data...")
    print(f"{'='*70}")
    train_inputs, train_masks = preprocessing_for_bert(X_train, tokenizer, Config.MAX_LEN)
    val_inputs, val_masks = preprocessing_for_bert(X_val, tokenizer, Config.MAX_LEN)
    print("✓ Tokenization complete")

    # Create DataLoaders
    train_labels = torch.tensor(y_train)
    val_labels = torch.tensor(y_val)

    train_data = TensorDataset(train_inputs, train_masks, train_labels)
    train_sampler = RandomSampler(train_data)
    train_dataloader = DataLoader(train_data, sampler=train_sampler, batch_size=Config.BATCH_SIZE)

    val_data = TensorDataset(val_inputs, val_masks, val_labels)
    val_sampler = SequentialSampler(val_data)
    val_dataloader = DataLoader(val_data, sampler=val_sampler, batch_size=Config.BATCH_SIZE)

    # Initialize model
    print(f"\n{'='*70}")
    print("Initializing model...")
    print(f"{'='*70}")
    bert_classifier, optimizer, scheduler = initialize_model(Config.EPOCHS, device)

    # Update scheduler with correct number of steps
    total_steps = len(train_dataloader) * Config.EPOCHS
    scheduler = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=0,
        num_training_steps=total_steps
    )

    print(f"✓ Model initialized")
    print(f"  - Total parameters: {sum(p.numel() for p in bert_classifier.parameters()):,}")
    print(f"  - Trainable parameters: {sum(p.numel() for p in bert_classifier.parameters() if p.requires_grad):,}")

    # Loss function
    loss_fn = nn.CrossEntropyLoss()

    # Train model
    train(
        bert_classifier, train_dataloader, val_dataloader,
        optimizer, scheduler, loss_fn,
        Config.EPOCHS, device, evaluation=True
    )

    # ========================================================================
    # Testing
    # ========================================================================

    print(f"\n{'='*70}")
    print("TESTING PHASE")
    print(f"{'='*70}\n")

    # Load test data
    test_df = pd.read_csv(Config.TEST_FILE)
    test_df.fillna('', inplace=True)
    test_df['label'] = test_df['Category'].apply(lambda x: 1 if x == 'Positive' else 0)

    print(f"Test set size: {len(test_df)}")
    print(f"Test label distribution:\n{test_df['label'].value_counts()}\n")

    # Test 1: Text only (no features)
    print("-"*70)
    print("Test 1: Text only (baseline)")
    print("-"*70)
    test_df_text_only = test_df.copy()
    test_df_text_only['tweet'] = test_df_text_only['text']

    test_inputs, test_masks = preprocessing_for_bert(
        test_df_text_only.tweet.values, tokenizer, Config.MAX_LEN
    )
    test_dataset = TensorDataset(test_inputs, test_masks)
    test_dataloader = DataLoader(test_dataset, sampler=SequentialSampler(test_dataset), batch_size=Config.BATCH_SIZE)

    probs_text_only = bert_predict(bert_classifier, test_dataloader, device)
    evaluate_roc(probs_text_only, test_df['label'].values, threshold=0.5)

    # Test 2: Text + Features
    print("-"*70)
    print("Test 2: Text + Features (main result)")
    print("-"*70)
    test_df_with_features = test_df.copy()
    test_df_with_features['tweet'] = test_df_with_features.text.astype(str).str.cat(
        test_df_with_features.phrase.astype(str), sep=', '
    )

    test_inputs, test_masks = preprocessing_for_bert(
        test_df_with_features.tweet.values, tokenizer, Config.MAX_LEN
    )
    test_dataset = TensorDataset(test_inputs, test_masks)
    test_dataloader = DataLoader(test_dataset, sampler=SequentialSampler(test_dataset), batch_size=Config.BATCH_SIZE)

    probs_with_features = bert_predict(bert_classifier, test_dataloader, device)
    evaluate_roc(probs_with_features, test_df['label'].values, threshold=0.5)

    # Generate predictions with custom threshold
    print("-"*70)
    print(f"Predictions with threshold={Config.PREDICTION_THRESHOLD}")
    print("-"*70)
    preds = np.where(probs_with_features[:, 1] > Config.PREDICTION_THRESHOLD, 1, 0)
    print(f"Samples predicted as positive: {preds.sum()} / {len(preds)}")

    # Save predictions
    output = test_df_with_features.copy()
    output['predicted_label'] = preds
    output['predicted_prob'] = probs_with_features[:, 1]
    output.to_csv('predictions_with_features.csv', index=False)
    print("✓ Predictions saved to 'predictions_with_features.csv'")

    print("\n" + "="*70)
    print("EXPERIMENT COMPLETE")
    print("="*70)

if __name__ == "__main__":
    main()
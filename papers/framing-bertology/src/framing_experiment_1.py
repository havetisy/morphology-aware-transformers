def bert_predict(model, test_dataloader, device):
    """
    Make predictions on test set

    Args:
        model: Trained BertClassifier
        test_dataloader: DataLoader for test data
        device: torch device

    Returns:
        probs: Array of predicted probabilities (N, 2)
    """
    model.eval()
    all_logits = []

    for batch in test_dataloader:
        b_input_ids, b_attn_mask = tuple(t.to(device) for t in batch)[:2]

        with torch.no_grad():
            logits = model(b_input_ids, b_attn_mask)
        all_logits.append(logits)

    all_logits = torch.cat(all_logits, dim=0)
    probs = F.softmax(all_logits, dim=1).cpu().numpy()

    return probs

def evaluate_roc(probs, y_true, threshold=0.5):
    """
    Evaluate predictions and plot ROC curve

    Args:
        probs: Array of predicted probabilities
        y_true: True labels
        threshold: Classification threshold
    """
    preds = probs[:, 1]
    fpr, tpr, thresholds = roc_curve(y_true, preds)
    roc_auc = auc(fpr, tpr)

    print(f'\nAUC: {roc_auc:.4f}')

    y_pred = np.where(preds >= threshold, 1, 0)
    accuracy = accuracy_score(y_true, y_pred)
    print(f'Accuracy (threshold={threshold}): {accuracy*100:.2f}%\n')

    # Plot ROC curve
    plt.figure(figsize=(8, 6))
    plt.title('Receiver Operating Characteristic')
    plt.plot(fpr, tpr, 'b', label=f'AUC = {roc_auc:.2f}')
    plt.legend(loc='lower right')
    plt.plot([0, 1], [0, 1], 'r--')
    plt.xlim([0, 1])
    plt.ylim([0, 1])
    plt.ylabel('True Positive Rate')
    plt.xlabel('False Positive Rate')
    plt.grid(alpha=0.3)
    plt.show()


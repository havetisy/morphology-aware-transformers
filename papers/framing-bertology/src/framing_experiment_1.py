def load_and_prepare_data(filepath, include_features=True):
    """
    Load dataset and prepare for training

    Args:
        filepath: Path to CSV file
        include_features: If True, concatenate 'phrase' column to 'text'

    Returns:
        DataFrame with prepared data
    """
    df = pd.read_csv(filepath)
    df.fillna('', inplace=True)

    # Create binary labels (1=Positive/framing, 0=Negative/no framing)
    df['label'] = df['Category'].apply(lambda x: 1 if x == 'Positive' else 0)

    if include_features:
        # KEY STEP: Concatenate text with linguistic features
        df['tweet'] = df.text.astype(str).str.cat(df.phrase.astype(str), sep=', ')
        print("✓ Features concatenated to text")
    else:
        df['tweet'] = df['text']
        print("✓ Using text only (no features)")

    print(f"Dataset shape: {df.shape}")
    print(f"Label distribution:\n{df['label'].value_counts()}")

    return df

def text_preprocessing(text):
    """
    Basic text cleaning

    Args:
        text: Input string

    Returns:
        Cleaned string
    """
    # Remove '@mentions'
    text = re.sub(r'(@.*?)[\s]', ' ', text)
    # Replace '&amp;' with '&'
    text = re.sub(r'&amp;', '&', text)
    # Remove trailing whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def preprocessing_for_bert(data, tokenizer, max_len):
    """
    Tokenize and encode data for BERT

    Args:
        data: Array of text strings
        tokenizer: BERT tokenizer
        max_len: Maximum sequence length

    Returns:
        input_ids: Tensor of token IDs
        attention_masks: Tensor of attention masks
    """
    input_ids = []
    attention_masks = []

    for sent in data:
        encoded_sent = tokenizer.encode_plus(
            text=text_preprocessing(sent),
            add_special_tokens=True,    # Add [CLS] and [SEP]
            max_length=max_len,
            pad_to_max_length=True,
            return_attention_mask=True,
            truncation=True
        )

        input_ids.append(encoded_sent.get('input_ids'))
        attention_masks.append(encoded_sent.get('attention_mask'))

    # Convert to tensors
    input_ids = torch.tensor(input_ids)
    attention_masks = torch.tensor(attention_masks)

    return input_ids, attention_masks


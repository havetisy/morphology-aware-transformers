class BertClassifier(nn.Module):
    """
    BERT-based binary classifier

    Architecture:
        BERT encoder -> Dropout -> Linear(768, 2)
    """

    def __init__(self, freeze_bert=False):
        """
        Args:
            freeze_bert: If True, freeze BERT parameters during training
        """
        super(BertClassifier, self).__init__()

        # BERT model
        self.bert = BertModel.from_pretrained('bert-base-uncased')

        # Dropout for regularization
        self.dropout = nn.Dropout(0.1)

        # Classification layer
        self.linear = nn.Linear(768, 2)  # BERT hidden size is 768

        # Optionally freeze BERT parameters
        if freeze_bert:
            for param in self.bert.parameters():
                param.requires_grad = False

    def forward(self, input_ids, attention_mask):
        """
        Forward pass

        Args:
            input_ids: Tensor of token IDs
            attention_mask: Tensor of attention masks

        Returns:
            logits: Tensor of shape (batch_size, 2)
        """
        # BERT encoding
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask)

        # Use [CLS] token representation
        pooled_output = outputs.pooler_output

        # Apply dropout and linear layer
        output = self.dropout(pooled_output)
        logits = self.linear(output)

        return logits


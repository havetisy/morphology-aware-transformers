def initialize_model(epochs, device):
    """
    Initialize model, optimizer, and learning rate scheduler

    Args:
        epochs: Number of training epochs
        device: torch device

    Returns:
        model: BertClassifier instance
        optimizer: AdamW optimizer
        scheduler: Linear warmup scheduler
    """
    # Initialize model
    bert_classifier = BertClassifier(freeze_bert=False)
    bert_classifier.to(device)

    # Optimizer
    optimizer = AdamW(
        bert_classifier.parameters(),
        lr=Config.LEARNING_RATE,
        eps=1e-8
    )

    # Learning rate scheduler with warmup
    total_steps = epochs * 100  # Approximate - will be corrected later
    scheduler = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=0,
        num_training_steps=total_steps
    )

    return bert_classifier, optimizer, scheduler

def set_seed(seed_value=42):
    """Set seed for reproducibility"""
    random.seed(seed_value)
    np.random.seed(seed_value)
    torch.manual_seed(seed_value)
    torch.cuda.manual_seed_all(seed_value)

def train(model, train_dataloader, val_dataloader, optimizer, scheduler,
          loss_fn, epochs, device, evaluation=True):
    """
    Train the BERT classifier

    Args:
        model: BertClassifier instance
        train_dataloader: DataLoader for training data
        val_dataloader: DataLoader for validation data
        optimizer: Optimizer
        scheduler: Learning rate scheduler
        loss_fn: Loss function
        epochs: Number of epochs
        device: torch device
        evaluation: If True, evaluate on validation set after each epoch
    """
    print("="*70)
    print("Starting training...")
    print("="*70)

    for epoch_i in range(epochs):
        # =======================================
        #               Training
        # =======================================
        print(f"\n{'Epoch':^7} | {'Batch':^7} | {'Train Loss':^12} | {'Val Loss':^10} | {'Val Acc':^9} | {'Elapsed':^9}")
        print("-"*70)

        t0_epoch = time.time()
        t0_batch = time.time()

        total_loss = 0
        batch_loss = 0
        batch_counts = 0

        model.train()

        for step, batch in enumerate(train_dataloader):
            batch_counts += 1

            # Load batch to device
            b_input_ids, b_attn_mask, b_labels = tuple(t.to(device) for t in batch)

            # Zero gradients
            model.zero_grad()

            # Forward pass
            logits = model(b_input_ids, b_attn_mask)

            # Compute loss
            loss = loss_fn(logits, b_labels)
            batch_loss += loss.item()
            total_loss += loss.item()

            # Backward pass
            loss.backward()

            # Clip gradients to prevent exploding gradients
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)

            # Update parameters
            optimizer.step()
            scheduler.step()

            # Print progress every 20 batches
            if (step % 20 == 0 and step != 0) or (step == len(train_dataloader) - 1):
                time_elapsed = time.time() - t0_batch
                print(f"{epoch_i + 1:^7} | {step:^7} | {batch_loss / batch_counts:^12.6f} | {'-':^10} | {'-':^9} | {time_elapsed:^9.2f}")

                batch_loss = 0
                batch_counts = 0
                t0_batch = time.time()

        avg_train_loss = total_loss / len(train_dataloader)

        print("-"*70)

        # =======================================
        #               Evaluation
        # =======================================
        if evaluation:
            val_loss, val_accuracy = evaluate(model, val_dataloader, loss_fn, device)
            time_elapsed = time.time() - t0_epoch

            print(f"{epoch_i + 1:^7} | {'-':^7} | {avg_train_loss:^12.6f} | {val_loss:^10.6f} | {val_accuracy:^9.2f} | {time_elapsed:^9.2f}")
            print("-"*70)

    print("\n" + "="*70)
    print("Training complete!")
    print("="*70)

def evaluate(model, val_dataloader, loss_fn, device):
    """
    Evaluate model on validation set

    Args:
        model: BertClassifier instance
        val_dataloader: DataLoader for validation data
        loss_fn: Loss function
        device: torch device

    Returns:
        avg_val_loss: Average validation loss
        avg_val_accuracy: Average validation accuracy (%)
    """
    model.eval()

    val_accuracy = []
    val_loss = []

    for batch in val_dataloader:
        b_input_ids, b_attn_mask, b_labels = tuple(t.to(device) for t in batch)

        with torch.no_grad():
            logits = model(b_input_ids, b_attn_mask)

        loss = loss_fn(logits, b_labels)
        val_loss.append(loss.item())

        preds = torch.argmax(logits, dim=1).flatten()
        accuracy = (preds == b_labels).cpu().numpy().mean() * 100
        val_accuracy.append(accuracy)

    avg_val_loss = np.mean(val_loss)
    avg_val_accuracy = np.mean(val_accuracy)

    return avg_val_loss, avg_val_accuracy


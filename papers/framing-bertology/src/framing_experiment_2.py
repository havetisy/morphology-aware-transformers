import torch.nn as nn
from transformers import BertModel

class BertClassifier(nn.Module):
    """BERT-based binary classifier"""

    def __init__(self, freeze_bert=False):
        super(BertClassifier, self).__init__()

        # NOTE: We still use bert-base-uncased for the model
        # The custom tokenizer has more tokens, but the model architecture is same
        self.bert = BertModel.from_pretrained('bert-base-uncased')

        # IMPORTANT: Resize embeddings to match our custom tokenizer!
        self.bert.resize_token_embeddings(len(tokenizer_GAMEfBERT))

        self.dropout = nn.Dropout(0.1)
        self.linear = nn.Linear(768, 2)

        if freeze_bert:
            for param in self.bert.parameters():
                param.requires_grad = False

    def forward(self, input_ids, attention_mask):
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        pooled_output = outputs.pooler_output
        output = self.dropout(pooled_output)
        logits = self.linear(output)
        return logits

